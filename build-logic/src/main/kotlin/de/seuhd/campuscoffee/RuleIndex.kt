package de.seuhd.campuscoffee

import org.yaml.snakeyaml.Yaml

/**
 * The lists of the rule files in `CLAUDE.md` and `AGENTS.md`, generated from the front matter (`description` and
 * `paths`) of the files in `.claude/rules/`, between the lines [BEGIN] and [END].
 */
class RuleIndex(
    rules: Map<String, List<String>>,
    private val lineLength: Int
) {
    private val rules =
        rules.toSortedMap().map { (name, lines) ->
            val frontMatter = lines.drop(1).takeWhile { it != "---" }.joinToString("\n")
            val yaml = Yaml().load<Map<String, Any?>>(frontMatter).orEmpty()
            Rule(
                name = name,
                description = yaml["description"] as String? ?: error(".claude/rules/$name has no description."),
                paths = (yaml["paths"] as List<*>?)?.map { it.toString() } ?: error(".claude/rules/$name has no paths.")
            )
        }

    /**
     * @param target the name of the file, CLAUDE.md or AGENTS.md
     * @param text the content of the file, of which only the generated list changes
     */
    fun render(
        target: String,
        text: String
    ): String {
        val start = text.indexOf(BEGIN)
        val end = text.indexOf(END)
        require(start in 0..<end) { "$target has no lines $BEGIN and $END." }
        val list =
            if (target == "AGENTS.md") {
                listOf("| Rule file | Read it before you change | Content |", "|---|---|---|") +
                    rules.map {
                        "| `.claude/rules/${it.name}` | ${it.paths.joinToString { p ->
                            "`$p`"
                        }} | ${it.description} |"
                    }
            } else {
                rules.flatMap { wrap("- `${it.name}`: ${it.description}") }
            }
        return text.substring(0, start) + BEGIN + "\n" + list.joinToString("\n") + "\n" + text.substring(end)
    }

    private fun wrap(text: String): List<String> =
        text.split(" ").fold(listOf()) { lines, word ->
            val last = lines.lastOrNull()
            when {
                last == null -> listOf(word)
                last.length + 1 + word.length > lineLength -> lines + "  $word"
                else -> lines.dropLast(1) + "$last $word"
            }
        }

    private data class Rule(
        val name: String,
        val description: String,
        val paths: List<String>
    )

    companion object {
        const val BEGIN = "<!-- Generated by gradle ruleIndex from the front matter of .claude/rules/*.md. -->"
        const val END = "<!-- End of the generated list. -->"
    }
}
